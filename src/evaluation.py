"""
Model Evaluation Module for Student Performance Analytics.
Generates:
- Actual Test Set Metric Tables (MAE, MSE, RMSE, R² Score)
- Evaluation Charts (saved to outputs/charts/):
  1. Training Loss & Validation Loss vs Epoch Curve
  2. Actual vs Predicted Grades Scatter Plot (with y=x reference line)
  3. Prediction Error Distribution (Residuals Histogram & KDE)
  4. Baseline vs Deep Learning Comparison Bar Chart
- Overfitting and Underfitting Diagnostic Analysis
- Academic Performance Interpretation and Small-Dataset Limitations
"""

import os
import json
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
import plotly.express as px
import plotly.graph_objects as go

CHARTS_DIR = os.path.join(os.path.dirname(os.path.dirname(__file__)), "outputs", "charts")
RESULTS_DIR = os.path.join(os.path.dirname(os.path.dirname(__file__)), "outputs", "results")
os.makedirs(CHARTS_DIR, exist_ok=True)


def load_model_results(results_path=None):
    """Loads results generated by model.py"""
    if results_path is None:
        results_path = os.path.join(RESULTS_DIR, "model_results.json")
    if not os.path.exists(results_path):
        raise FileNotFoundError(f"Model results file not found at {results_path}. Run model.py first.")
    with open(results_path, "r") as f:
        return json.load(f)


def plot_loss_curves(results, save=True):
    """1 & 2. Training Loss and Validation Loss versus Epoch"""
    history = results["history"]
    epochs = range(1, len(history["loss"]) + 1)

    fig, ax = plt.subplots(figsize=(8, 5))
    ax.plot(epochs, history["loss"], label="Training Loss (MSE)", color="#1f77b4", linewidth=2.5)
    ax.plot(epochs, history["val_loss"], label="Validation Loss (MSE)", color="#ff7f0e", linewidth=2.5, linestyle="--")

    # Annotate minimum validation loss point
    min_val_idx = int(np.argmin(history["val_loss"]))
    min_val_loss = history["val_loss"][min_val_idx]
    ax.scatter([min_val_idx + 1], [min_val_loss], color="red", s=80, zorder=5, label=f"Best Val Epoch: {min_val_idx+1}")

    ax.set_title("Training Loss vs. Validation Loss across Epochs", fontsize=12, fontweight="bold", pad=10)
    ax.set_xlabel("Epoch Number", fontsize=11)
    ax.set_ylabel("Mean Squared Error (MSE)", fontsize=11)
    ax.legend(loc="upper right")
    plt.tight_layout()

    path = os.path.join(CHARTS_DIR, "eval_loss_curves.png")
    if save:
        fig.savefig(path, dpi=300)
        plt.close(fig)
    return fig, path


def plot_actual_vs_predicted(results, save=True):
    """3. Actual versus Predicted Grades Scatter Plot"""
    y_actual = np.array(results["test_actual"])
    y_pred = np.array(results["test_predicted_mlp"])
    r2 = results["mlp_test_metrics"]["R2"]
    mae = results["mlp_test_metrics"]["MAE"]

    fig, ax = plt.subplots(figsize=(8, 6))
    ax.scatter(y_actual, y_pred, alpha=0.7, color="#2b5c8f", edgecolors="black", s=60, label="Test Students")

    # Reference y=x ideal line
    min_val = min(y_actual.min(), y_pred.min(), 0)
    max_val = max(y_actual.max(), y_pred.max(), 20)
    ax.plot([min_val, max_val], [min_val, max_val], color="red", linestyle="--", linewidth=2, label="Perfect Fit (y = x)")

    ax.set_title(f"Actual vs. Predicted Final Grade (Test Set: R² = {r2:.3f}, MAE = {mae:.2f})", fontsize=12, fontweight="bold", pad=10)
    ax.set_xlabel("Actual Final Grade (G3: 0 to 20)", fontsize=11)
    ax.set_ylabel("Predicted Final Grade (G3: 0 to 20)", fontsize=11)
    ax.set_xlim(-1, 21)
    ax.set_ylim(-1, 21)
    ax.legend(loc="upper left")
    plt.tight_layout()

    path = os.path.join(CHARTS_DIR, "eval_actual_vs_predicted.png")
    if save:
        fig.savefig(path, dpi=300)
        plt.close(fig)
    return fig, path


def plot_prediction_error_distribution(results, save=True):
    """4. Prediction Error (Residuals) Distribution"""
    y_actual = np.array(results["test_actual"])
    y_pred = np.array(results["test_predicted_mlp"])
    residuals = y_actual - y_pred

    fig, ax = plt.subplots(figsize=(8, 5))
    sns.histplot(residuals, bins=15, kde=True, color="#4c72b0", edgecolor="black", ax=ax)
    ax.axvline(0, color="red", linestyle="--", linewidth=2, label="Zero Error Line")
    mean_err = residuals.mean()
    std_err = residuals.std()
    ax.axvline(mean_err, color="green", linestyle="-.", linewidth=1.5, label=f"Mean Error: {mean_err:.2f}")

    ax.set_title(f"Prediction Error Distribution (Residuals: Mean = {mean_err:.2f}, Std = {std_err:.2f})", fontsize=12, fontweight="bold", pad=10)
    ax.set_xlabel("Prediction Error (Residual = Actual - Predicted)", fontsize=11)
    ax.set_ylabel("Frequency", fontsize=11)
    ax.legend()
    plt.tight_layout()

    path = os.path.join(CHARTS_DIR, "eval_error_distribution.png")
    if save:
        fig.savefig(path, dpi=300)
        plt.close(fig)
    return fig, path


def plot_model_comparison(results, save=True):
    """Baseline vs Deep Learning Comparison Bar Chart"""
    models = ["Linear Regression", "Random Forest", "Deep Learning (MLP)", "Early MLP (No G1/G2)"]
    mae_vals = [
        results["baseline_metrics"]["Linear_Regression"]["MAE"],
        results["baseline_metrics"]["Random_Forest"]["MAE"],
        results["mlp_test_metrics"]["MAE"],
        results["early_prediction_metrics"]["MAE"]
    ]
    rmse_vals = [
        results["baseline_metrics"]["Linear_Regression"]["RMSE"],
        results["baseline_metrics"]["Random_Forest"]["RMSE"],
        results["mlp_test_metrics"]["RMSE"],
        results["early_prediction_metrics"]["RMSE"]
    ]

    x = np.arange(len(models))
    width = 0.35

    fig, ax = plt.subplots(figsize=(9, 5))
    bars1 = ax.bar(x - width/2, mae_vals, width, label="MAE", color="#3b6998", edgecolor="black")
    bars2 = ax.bar(x + width/2, rmse_vals, width, label="RMSE", color="#e8743b", edgecolor="black")

    ax.set_title("Model Benchmark Comparison on Test Set (Lower is Better)", fontsize=12, fontweight="bold", pad=10)
    ax.set_ylabel("Error Metric Value", fontsize=11)
    ax.set_xticks(x)
    ax.set_xticklabels(models, fontsize=10)
    ax.legend()

    # Annotate bar values
    for b in bars1:
        h = b.get_height()
        ax.annotate(f"{h:.2f}", xy=(b.get_x() + b.get_width()/2, h), xytext=(0, 3), textcoords="offset points", ha='center', va='bottom', fontsize=9)
    for b in bars2:
        h = b.get_height()
        ax.annotate(f"{h:.2f}", xy=(b.get_x() + b.get_width()/2, h), xytext=(0, 3), textcoords="offset points", ha='center', va='bottom', fontsize=9)

    plt.tight_layout()
    path = os.path.join(CHARTS_DIR, "eval_baseline_comparison.png")
    if save:
        fig.savefig(path, dpi=300)
        plt.close(fig)
    return fig, path


def generate_evaluation_diagnostics(results):
    """
    Computes formal overfitting, underfitting, and diagnostic analysis.
    """
    history = results["history"]
    mlp_metrics = results["mlp_test_metrics"]
    final_train_loss = history["loss"][-1]
    final_val_loss = history["val_loss"][-1]
    loss_ratio = final_val_loss / (final_train_loss + 1e-6)

    # Overfitting assessment
    if loss_ratio > 1.8:
        overfit_status = "Moderate Overfitting Detected"
        overfit_desc = "Validation loss exceeds training loss substantially, indicating the model captured training sample noise."
    elif loss_ratio > 1.2:
        overfit_status = "Controlled / Mild Generalization Gap"
        overfit_desc = "Validation loss closely tracks training loss with acceptable regularization gap achieved via Dropout (0.2) and EarlyStopping."
    else:
        overfit_status = "No Significant Overfitting"
        overfit_desc = "Validation loss closely matches training loss, demonstrating consistent generalization."

    # Underfitting assessment
    if mlp_metrics["R2"] < 0.4:
        underfit_status = "Underfitting Present"
        underfit_desc = "Model explains insufficient variance in final grades."
    else:
        underfit_status = "No Underfitting"
        underfit_desc = f"Model captures substantial grade variance (R² = {mlp_metrics['R2']:.3f}), achieving high predictive fidelity."

    comparison_df = pd.DataFrame([
        {"Model": "Linear Regression (Baseline)", "MAE": results["baseline_metrics"]["Linear_Regression"]["MAE"], "RMSE": results["baseline_metrics"]["Linear_Regression"]["RMSE"], "R2": results["baseline_metrics"]["Linear_Regression"]["R2"]},
        {"Model": "Random Forest Regressor", "MAE": results["baseline_metrics"]["Random_Forest"]["MAE"], "RMSE": results["baseline_metrics"]["Random_Forest"]["RMSE"], "R2": results["baseline_metrics"]["Random_Forest"]["R2"]},
        {"Model": "Deep Learning MLP (Best Model)", "MAE": mlp_metrics["MAE"], "RMSE": mlp_metrics["RMSE"], "R2": mlp_metrics["R2"]},
        {"Model": "Early Prediction MLP (Excl. G1/G2)", "MAE": results["early_prediction_metrics"]["MAE"], "RMSE": results["early_prediction_metrics"]["RMSE"], "R2": results["early_prediction_metrics"]["R2"]}
    ])

    return {
        "overfit_status": overfit_status,
        "overfit_desc": overfit_desc,
        "underfit_status": underfit_status,
        "underfit_desc": underfit_desc,
        "comparison_table": comparison_df,
        "loss_ratio": round(float(loss_ratio), 3),
        "final_train_loss": round(float(final_train_loss), 3),
        "final_val_loss": round(float(final_val_loss), 3)
    }


def generate_all_evaluation_artifacts(results=None):
    """
    Generates all 4 evaluation plots and diagnostic metrics.
    """
    if results is None:
        results = load_model_results()

    _, p1 = plot_loss_curves(results, save=True)
    _, p2 = plot_actual_vs_predicted(results, save=True)
    _, p3 = plot_prediction_error_distribution(results, save=True)
    _, p4 = plot_model_comparison(results, save=True)

    diagnostics = generate_evaluation_diagnostics(results)
    return {
        "chart_paths": {"loss_curves": p1, "actual_vs_predicted": p2, "residuals": p3, "model_comparison": p4},
        "diagnostics": diagnostics
    }


if __name__ == "__main__":
    arts = generate_all_evaluation_artifacts()
    print("Evaluation artifacts created successfully!")
    print("Diagnostics:")
    print("Overfitting:", arts["diagnostics"]["overfit_status"])
    print("Underfitting:", arts["diagnostics"]["underfit_status"])
    print("\nModel Comparison Table:\n", arts["diagnostics"]["comparison_table"])
